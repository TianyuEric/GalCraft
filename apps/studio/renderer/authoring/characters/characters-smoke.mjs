import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
const require = createRequire(process.env.GALCRAFT_PLAYWRIGHT_PACKAGE ?? import.meta.url);
const { chromium } = require('playwright');
const output = resolve('test-results/latest/round6/characters'); await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
const errors = [], checks = []; page.on('pageerror', error => errors.push(String(error)));
try {
  await page.goto('http://127.0.0.1:6007/iframe.html?id=product-studio-authoring-characters--global-roles&viewMode=story');
  await page.locator('.character-manager').waitFor();
  assert.match(await page.locator('.character-warning').innerText(), /旧作品/);
  await page.screenshot({ path: join(output, 'unclassified.png'), animations: 'disabled' });
  await page.locator('input[value="main"]').check();
  await page.locator('.character-route input[type="checkbox"]').first().check();
  await page.locator('.character-route-columns fieldset').last().locator('input').first().check();
  await page.screenshot({ path: join(output, 'main-route.png'), animations: 'disabled' });
  await page.getByRole('button', { name: '应用修改 (1)', exact: true }).click();
  await page.locator('.character-saved').waitFor();
  assert.match(await page.locator('.character-manager-list button.selected').innerText(), /主角色/);
  await page.getByRole('button', { name: '撤销', exact: true }).click();
  await page.locator('.character-warning').waitFor();
  assert.match(await page.locator('.character-manager-list button.selected').innerText(), /未分类/);
  await page.getByRole('button', { name: '重做', exact: true }).click();
  await page.locator('.character-route').waitFor();
  checks.push('legacy classification, route and ending selection, apply, undo and redo');
  await page.getByRole('button', { name: '新增角色', exact: true }).click();
  await page.locator('.gc-dialog header button').click();
  await page.getByRole('button', { name: '继续编辑', exact: true }).click();
  assert.equal(await page.getByRole('dialog').count(), 1);
  assert(await page.locator('.character-manager').isVisible());
  assert(await page.getByRole('button', { name: '应用修改 (1)', exact: true }).isEnabled());
  await page.keyboard.press('Escape');
  await page.getByRole('button', { name: '继续编辑', exact: true }).click();
  assert(await page.locator('.character-manager').isVisible());
  checks.push('new character draft remains available after cancelling close');
  await page.goto('http://127.0.0.1:6007/iframe.html?id=product-studio-authoring-characters--japanese-dark&viewMode=story');
  await page.setViewportSize({ width: 900, height: 600 });
  await page.locator('.character-manager').waitFor();
  await page.locator('input[value="main"]').check();
  const footer = await page.locator('.character-manager-footer').boundingBox();
  assert(footer.y >= 0 && footer.y + footer.height <= 600);
  await page.locator('.gc-dialog-body').evaluate(element => { element.scrollTop = 0; });
  await page.screenshot({ path: join(output, 'japanese-dark.png'), animations: 'disabled' });
  checks.push('Japanese dark appearance and reachable footer at 900x600');
  assert.deepEqual(errors, []);
  await writeFile(join(output, 'report.json'), JSON.stringify({ target: 'Character manager Storybook component in Chrome', result: 'passed', checks, errors, executedAt: new Date().toISOString() }, null, 2));
  console.log(JSON.stringify({ result: 'passed', checks, output }));
} finally { await browser.close(); }
