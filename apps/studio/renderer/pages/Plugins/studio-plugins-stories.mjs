import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
const require = createRequire(process.env.GALCRAFT_PLAYWRIGHT_PACKAGE ?? import.meta.url);
const { chromium } = require('playwright');
const output = resolve('test-results/latest/studio-plugins'), browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 900, height: 700 } });
const report = { target: 'storybookVisual', viewport: '900x700', checks: [], errors: [], result: 'failed', executedAt: new Date().toISOString() };
page.on('pageerror', error => report.errors.push(String(error)));
await mkdir(output, { recursive: true });
try {
  const story = async name => { await page.goto(`http://127.0.0.1:6007/iframe.html?id=product-studio-plugins-plugin-contributions--${name}&viewMode=story`); };
  await story('author-setup');
  await page.getByLabel('入口标题', { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: join(output, 'story-author-setup.png'), fullPage: true });
  const preview = page.getByRole('button', { name: '预览发送上下文', exact: true });
  await preview.click(); await page.locator('.epilogue-preview section').first().waitFor();
  const dialog = page.getByRole('dialog');
  assert.equal(await dialog.evaluate(node => node.getBoundingClientRect().height <= innerHeight), true);
  assert.equal(await dialog.locator('pre').isVisible(), false);
  assert(await dialog.getByText('许可角色设定', { exact: true }).isVisible());
  await dialog.evaluate(async node => { await Promise.all(node.getAnimations({ subtree: true }).map(animation => animation.finished.catch(() => {}))); });
  await page.screenshot({ path: join(output, 'story-context-preview.png'), fullPage: true });
  await page.keyboard.press('Tab');
  assert.equal(await dialog.evaluate(node => node.contains(document.activeElement)), true);
  await page.keyboard.press('Escape'); await dialog.waitFor({ state: 'detached' });
  assert.equal(await preview.evaluate(node => document.activeElement === node), true);
  const editedTitle = '杏的夏日 · 路由切换保留许可草稿'; await page.getByLabel('入口标题', { exact: true }).fill(editedTitle);
  await page.getByRole('button', { name: 'Storybook: 暂时离开工作台', exact: true }).click();
  assert.equal(await page.getByLabel('入口标题', { exact: true }).count(), 0);
  await page.getByRole('button', { name: 'Storybook: 返回工作台', exact: true }).click();
  assert.equal(await page.getByLabel('入口标题', { exact: true }).inputValue(), editedTitle);
  assert(await page.getByText('草稿 · 尚未应用', { exact: true }).isVisible());
  const apply = page.getByRole('button', { name: '应用到作品', exact: true });
  assert.equal(await apply.evaluate(node => { const rect = node.getBoundingClientRect(); return rect.top >= 0 && rect.bottom <= innerHeight; }), true);
  report.checks.push('900px light layout has a visible primary action and no horizontal overflow; preview shows names and permitted content with JSON collapsed; modal confines focus, Esc restores trigger; route unmount/remount retains draft');
  await story('japanese-dark'); await page.getByLabel('入口タイトル', { exact: true }).waitFor();
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: join(output, 'story-japanese-dark.png'), fullPage: true });
  report.checks.push('Japanese dark setup displays long names at 900px without horizontal overflow');
  await story('empty'); await page.getByRole('button', { name: '新增入口', exact: true }).waitFor();
  assert.equal(await page.getByRole('button', { name: '新增入口', exact: true }).isDisabled(), true);
  assert(await page.getByText('请先在创作页的角色资料中设置个人路线主角色和个人结局。', { exact: true }).isVisible());
  await page.screenshot({ path: join(output, 'story-empty.png'), fullPage: true });
  report.checks.push('empty setup explains role prerequisite and disables add');
  await story('edit-conflict'); await page.getByRole('button', { name: '应用到作品', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '作品内容已变化' }).waitFor();
  assert.equal(await page.getByLabel('入口标题', { exact: true }).inputValue(), '杏的夏日 · 雨停之后，我们再次相约');
  await page.screenshot({ path: join(output, 'story-edit-conflict.png'), fullPage: true });
  report.checks.push('revision conflict preserves author draft and displays recovery message');
  await story('removed-references'); await page.getByText('已移除素材', { exact: true }).waitFor();
  await page.getByRole('button', { name: '应用到作品', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: '请修正标出的字段' }).waitFor();
  await page.screenshot({ path: join(output, 'story-removed-references.png'), fullPage: true });
  const missingAsset = page.locator('[data-reference-id="00000000-0000-4000-8000-000000000004"]');
  await missingAsset.getByRole('button', { name: '替换', exact: true }).focus(); await page.keyboard.press('Enter');
  await page.locator('[data-reference-id="old-ending"]').getByRole('button', { name: '删除引用', exact: true }).focus(); await page.keyboard.press('Space');
  assert.equal(await page.evaluate(() => document.activeElement !== document.body), true);
  assert.equal(await page.getByText('已移除素材', { exact: true }).count(), 0); assert.equal(await page.getByText('已移除结局', { exact: true }).count(), 0);
  await page.getByLabel('搜索素材', { exact: true }).fill('钢琴');
  assert.equal(await page.locator('.epilogue-options').last().getByRole('checkbox').count(), 1);
  assert.equal(await page.locator('.epilogue-selected [data-reference-id]').count(), 3);
  await page.locator('.epilogue-options').last().getByRole('checkbox').focus(); await page.keyboard.press('Space');
  assert.equal(await page.locator('.epilogue-selected [data-reference-id]').count(), 4);
  report.checks.push('missing references remain visible and block apply; keyboard Enter replaces a missing asset, Space removes an ending and selects an asset, focus is retained; search does not hide the selected summary');
  for (const [name, label, action, error] of [['english-errors', 'Permitted character setting', 'Apply to project', 'Complete this field.'], ['japanese-errors', '許可するキャラ設定', '作品に適用', 'この項目を入力してください。']]) {
    await story(name); await page.getByLabel(label, { exact: true }).fill(''); await page.getByRole('button', { name: action, exact: true }).click();
    await page.getByText(error, { exact: true }).waitFor();
    assert.equal(await page.getByLabel(label, { exact: true }).getAttribute('aria-invalid'), 'true');
    assert.equal(await page.locator('.epilogue-error').evaluateAll(nodes => nodes.some(node => /请|后日谈|素材已移除|Error:/.test(node.textContent))), false);
    await page.screenshot({ path: join(output, `story-${name}.png`), fullPage: true });
  }
  report.checks.push('English and Japanese errors use localized persistent field feedback and retain invalid drafts');
  assert.deepEqual(report.errors, []); report.result = 'passed';
} catch (error) { report.error = error.stack ?? String(error); }
finally { await writeFile(join(output, 'storybook-report.json'), JSON.stringify(report, null, 2)); await browser.close(); console.log(JSON.stringify(report)); }
if (report.result !== 'passed') process.exitCode = 1;
