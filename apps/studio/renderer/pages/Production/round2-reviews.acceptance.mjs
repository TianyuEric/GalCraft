import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
const { chromium } = createRequire(import.meta.url)('playwright');
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1200, height: 900 } });
page.setDefaultTimeout(45000);
const output = 'test-results/latest/studio-round2/components'; await mkdir(output,{recursive:true});
const errors=[]; page.on('pageerror',e=>errors.push(e.message));
try {
 await page.goto('http://127.0.0.1:6007/iframe.html?id=product-studio-plugins-plugin-author-tools--round-2-documents&viewMode=story');
 await page.getByRole('button',{name:'编辑',exact:true}).first().click();
 await page.locator('.plugin-document-editor:visible input').first().fill('A 的未应用字段');
 await page.getByRole('tab',{name:'插件工具与文档',exact:true}).click();
 await page.getByRole('button',{name:'编辑',exact:true}).nth(1).click();
 await page.locator('.plugin-document-editor:visible input').first().fill('B 的未应用字段');
 await page.getByRole('tab',{name:/角色称呼/}).click();
 assert.equal(await page.locator('.plugin-document-editor:visible input').first().inputValue(),'A 的未应用字段');
 await page.getByRole('button',{name:'应用字段修改',exact:true}).click();
 await page.getByRole('alert').filter({hasText:'来源版本已变化'}).waitFor();
 assert.equal(await page.locator('[role=dialog],dialog').count(),0);
 await page.getByRole('button',{name:'关闭文档',exact:true}).click();
 await page.getByRole('alertdialog').waitFor();
 await page.getByRole('button',{name:'继续编辑',exact:true}).click();
 assert.equal(await page.locator('.plugin-document-editor:visible input').first().inputValue(),'A 的未应用字段');
 await page.screenshot({path:`${output}/w4-plugin-documents.png`});
 await page.goto('http://127.0.0.1:6007/iframe.html?id=product-studio-production-production-workflow--round-2-reviews&viewMode=story');
 await page.locator('.candidate-select').first().click();
 await page.getByRole('button',{name:'审阅采用',exact:true}).click();
 await page.locator('.production-review-document:visible').filter({hasText:'追加两条对白'}).waitFor();
 assert.equal(await page.locator('[role=dialog],dialog').count(),0);
 await page.getByRole('tab',{name:'制作工作台',exact:true}).click();
 await page.getByRole('tab',{name:'方案库',exact:true}).click();
 await page.getByRole('button',{name:'导入预设',exact:true}).click();
 await page.locator('.production-review-document:visible').filter({hasText:'确认导入'}).waitFor();
 await page.getByRole('button',{name:'确认导入',exact:true}).click();
 await page.getByRole('alert').filter({hasText:'导入暂时失败'}).waitFor();
 await page.getByRole('tab',{name:'采用审阅',exact:true}).click();
 await page.getByRole('button',{name:'采用到工作内容',exact:true}).click();
 await page.getByRole('alert').filter({hasText:'来源已变化'}).waitFor();
 await page.getByRole('tab',{name:'制作工作台',exact:true}).click();
 await page.getByRole('tab',{name:'制作与候选',exact:true}).click();
 await page.getByRole('button',{name:'审阅 UI 计划',exact:true}).click();
 await page.locator('.production-review-document:visible').filter({hasText:'准备计划'}).waitFor();
 await page.screenshot({path:`${output}/w4-production-reviews.png`});
 assert.deepEqual(errors,[]);
 await writeFile(`${output}/w4-reviews.json`,JSON.stringify({result:'passed',checks:['plugin A/B isolation','plugin conflict retains draft','cancel close retains input','adoption/import tabs','source conflict retained','UI plan central'],errors},null,2));
 console.log('W4 review documents passed');
} finally { await browser.close(); }
