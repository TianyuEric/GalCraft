import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
const { chromium } = createRequire(process.env.GALCRAFT_PLAYWRIGHT_PACKAGE ?? import.meta.url)('playwright');
const output = resolve('test-results/latest/workbench/production');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = [], checks = [];
page.on('pageerror', error => errors.push(error.message));
const story = async id => { await page.goto(`http://127.0.0.1:6007/iframe.html?id=product-studio-production-production-workflow--${id}&viewMode=story`); await page.locator('.production-page').waitFor(); };
const shot = name => page.screenshot({ path: join(output, `${name}.png`), animations: 'disabled' });
const start = async label => { await page.locator('.production-new-menu summary').click(); await page.locator('.production-new-options').getByRole('button', { name: label, exact: true }).click(); await page.locator('.production-workstation').waitFor(); };
try {
  await story('continuing-story');
  await page.locator('.conversation-panel').waitFor();
  await page.getByRole('textbox', { name: '本轮创作要求', exact: true }).fill('保留演出，只修改结尾。');
  assert(await page.getByRole('button', { name: '查看本轮发送计划' }).isEnabled());
  checks.push('existing conversation and candidate consumer remain reachable');
  await start('配音');
  await page.getByRole('textbox', { name: '朗读文本或逐行清单', exact: true }).fill('第一句\n第二句');
  await page.getByRole('button', { name: '按非空行拆分' }).click();
  assert.equal(await page.locator('.speech-lines tbody tr').count(), 2);
  assert.equal(await page.getByRole('dialog').count(), 0);
  assert.equal(await page.getByRole('textbox', { name: '本轮创作要求', exact: true }).count(), 0);
  await shot('speech-light'); checks.push('speech is a persistent typed input with stable per-line fields and no text-model form');
  await page.getByRole('tab', { name: '连接与工具', exact: true }).click();
  await page.getByRole('button', { name: '设置', exact: true }).first().click();
  await page.locator('.connection-workspace-editor').getByLabel('连接名称', { exact: true }).fill('保留的连接编辑');
  await page.getByRole('tab', { name: '制作与候选', exact: true }).click();
  assert.equal(await page.locator('.speech-lines tbody tr').count(), 2);
  await page.getByRole('tab', { name: '连接与工具', exact: true }).click();
  assert.equal(await page.getByLabel('连接名称', { exact: true }).inputValue(), '保留的连接编辑');
  await shot('persistent-connection'); checks.push('section switches preserve draft text and connection editing without a dialog');
  await story('continuing-story');
  await start('制作 UI 素材');
  assert.equal(await page.getByRole('textbox', { name: '正向提示', exact: true }).count(), 1);
  assert.equal(await page.getByLabel('Scene', { exact: true }).count(), 0);
  assert.equal(await page.getByLabel('Page', { exact: true }).count(), 0);
  await page.setViewportSize({ width: 900, height: 620 });
  await page.getByRole('button', { name: '参数', exact: true }).click();
  assert(await page.getByRole('button', { name: '返回输入', exact: true }).isVisible());
  await shot('ui-assets-narrow'); checks.push('UI raster has no scene or page requirement; narrow Inspector allocates space and has return navigation');
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.getByRole('tab', { name: '方案库', exact: true }).click();
  await page.locator('.production-library-row').first().click();
  for (const label of ['复制到个人', '复制到作品', '导出方案']) assert(await page.getByRole('button', { name: label, exact: true }).isVisible());
  assert.equal(await page.getByRole('dialog').count(), 0);
  await shot('scheme-library'); checks.push('real library component exposes its three management actions in the persistent document');
  await page.getByRole('button', { name: '新建预设', exact: true }).click();
  await page.getByLabel('预设名称', { exact: true }).fill('保留此处修改');
  await page.getByRole('button', { name: '新建制作方案', exact: true }).click();
  await page.getByRole('dialog', { name: '放弃未保存的方案修改？', exact: true }).waitFor();
  await page.getByRole('dialog', { name: '放弃未保存的方案修改？', exact: true }).getByRole('button', { name: '取消', exact: true }).click();
  assert.equal(await page.getByLabel('预设名称', { exact: true }).inputValue(), '保留此处修改');
  await page.locator('.production-library-row').nth(1).click();
  await page.getByRole('dialog', { name: '放弃未保存的方案修改？', exact: true }).waitFor();
  await page.getByRole('dialog', { name: '放弃未保存的方案修改？', exact: true }).getByRole('button', { name: '取消', exact: true }).click();
  assert.equal(await page.getByLabel('预设名称', { exact: true }).inputValue(), '保留此处修改');
  checks.push('new and open library entrypoints protect dirty scheme input through the shared discard decision');
  await story('dark-connections'); await start('生成背景'); await shot('background-dark');
  assert.deepEqual(errors, []);
  await writeFile(join(output, 'report.json'), JSON.stringify({ environment: 'Production React consumers with Storybook fixture bridge; no host persistence or service generation', result: 'passed', checks, errors, executedAt: new Date().toISOString() }, null, 2));
  console.log(JSON.stringify({ result: 'passed', checks, output }));
} finally { await browser.close(); }
