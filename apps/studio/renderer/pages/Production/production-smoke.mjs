import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';
const { chromium } = createRequire(process.env.GALCRAFT_PLAYWRIGHT_PACKAGE ?? import.meta.url)('playwright');
const output = resolve('test-results/latest/round6/production-components');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
const errors = [], checks = [];
page.on('pageerror', error => errors.push(error.message));
const story = async id => { await page.goto(`http://127.0.0.1:6007/iframe.html?id=product-studio-production-production-workflow--${id}&viewMode=story`); await page.locator('.production-page').waitFor(); };
const shot = name => page.screenshot({ path: join(output, `${name}.png`), animations: 'disabled' });
try {
  await story('continuing-story');
  await page.locator('.conversation-panel').waitFor();
  await page.getByRole('textbox', { name: '本轮创作要求' }).fill('保留前两段，只修改告别时的最后一句。');
  assert(await page.getByRole('button', { name: '查看本轮发送计划' }).isEnabled());
  await shot('continuing-story'); checks.push('selected complete version exposes continuation without changing direct creation');
  await page.getByRole('button', { name: '服务连接', exact: true }).click();
  await page.locator('.service-card').first().waitFor();
  assert.equal(await page.locator('.service-card').count(), 2);
  assert.equal(await page.getByRole('button', { name: '配置 DeepSeek', exact: true }).count(), 0);
  await shot('connections');
  await page.getByRole('button', { name: '添加服务', exact: true }).click();
  await page.getByRole('dialog').waitFor();
  await page.locator('.gc-choice-trigger').click();
  await page.locator('.gc-choice-search').fill('ComfyUI');
  await page.getByRole('option', { name: 'ComfyUI', exact: true }).click();
  assert.equal(await page.getByLabel('服务地址', { exact: true }).inputValue(), 'http://127.0.0.1:8188');
  assert.equal(await page.getByLabel('模型名称', { exact: true }).count(), 0);
  await page.setViewportSize({ width: 900, height: 600 });
  await shot('comfy-configuration');
  const footer = await page.locator('.gc-dialog-footer').boundingBox();
  assert(footer.y >= 0 && footer.y + footer.height <= 600);
  await page.getByRole('button', { name: '保存连接', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  assert.equal(await page.locator('.service-card').count(), 3);
  await page.getByRole('button', { name: '删除 ComfyUI', exact: true }).click();
  await page.getByRole('dialog').getByRole('button', { name: '删除连接', exact: true }).click();
  await page.getByRole('dialog').waitFor({ state: 'hidden' });
  assert.equal(await page.locator('.service-card').count(), 2);
  checks.push('unified provider selection, protocol-specific form, visible footer, save and delete');
  await story('many-tasks');
  assert.equal(await page.locator('.draft-row [data-task-id]').count(), 20);
  const overlap = await page.locator('.draft-row:has([data-task-id])').evaluateAll(rows => rows.some(row => {
    const a = row.querySelector('.task-row').getBoundingClientRect(), b = row.querySelector('.task-remove').getBoundingClientRect();
    return a.right > b.left + 1;
  }));
  assert.equal(overlap, false);
  await shot('many-tasks');
  await page.getByRole('textbox', { name: '搜索制作任务' }).fill('第 20 项');
  assert.equal(await page.locator('.draft-row [data-task-id]').count(), 1);
  checks.push('20 long task titles leave dedicated delete hit area and filter by name');
  await page.setViewportSize({ width: 1280, height: 900 });
  await story('dark-connections');
  await page.getByRole('button', { name: '服务连接', exact: true }).click(); await shot('connections-dark');
  assert.deepEqual(errors, []);
  await writeFile(join(output, 'report.json'), JSON.stringify({ environment: 'Storybook component fixtures in Chrome; no service calls', result: 'passed', checks, errors, executedAt: new Date().toISOString() }, null, 2));
  console.log(JSON.stringify({ result: 'passed', checks, output }));
} finally { await browser.close(); }
