import assert from 'node:assert/strict';
import { mkdir, rm, writeFile } from 'node:fs/promises';
import { join, resolve, sep } from 'node:path';
import { chromium } from 'playwright';
const output = resolve('test-results/latest/creator-restore'); await mkdir(output, { recursive: true });
const testingRoot = resolve('tmp/testing'), temporary = join(testingRoot, 'creator-restore-ui');
const clean = async () => { assert(temporary.startsWith(testingRoot + sep) && temporary === join(testingRoot, 'creator-restore-ui')); await rm(temporary, { recursive: true, force: true }); };
await clean(); await mkdir(temporary, { recursive: true });
process.env.TEMP = temporary; process.env.TMP = temporary;
let browser;
const errors = [];
try {
  browser = await chromium.launch({ channel: 'chrome', headless: true });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  page.on('pageerror', error => errors.push(String(error)));
  await page.goto('http://127.0.0.1:6007/iframe.html?id=product-studio-projects-restore-project--missing-dependency&viewMode=story');
  await page.getByRole('button', { name: '选择备份包', exact: true }).click();
  await page.getByRole('button', { name: '选择目标位置', exact: true }).click();
  await page.getByRole('radio', { name: '保留原作品身份', exact: false }).check();
  await page.getByRole('button', { name: '准备恢复并检查依赖', exact: true }).click();
  await page.getByRole('region', { name: '恢复检查报告', exact: true }).waitFor();
  assert(await page.getByRole('button', { name: '确认恢复并打开', exact: true }).isDisabled());
  await page.screenshot({ path: join(output, 'storybook-missing.png'), fullPage: true });
  await page.getByRole('button', { name: '导入本地目录', exact: true }).click();
  await page.getByText('检查已通过，可以确认恢复。', { exact: true }).waitFor();
  assert(await page.getByRole('button', { name: '确认恢复并打开', exact: true }).isEnabled());
  await page.getByRole('button', { name: '确认恢复并打开', exact: true }).click();
  await page.getByRole('button', { name: '打开恢复作品', exact: true }).waitFor();
  await page.screenshot({ path: join(output, 'storybook-receipt.png'), fullPage: true });
  await page.setViewportSize({ width: 900, height: 650 });
  await page.goto('http://127.0.0.1:6007/iframe.html?id=product-studio-projects-restore-project--dark-english&viewMode=story');
  await page.getByRole('button', { name: 'Choose backup', exact: true }).click();
  await page.getByRole('button', { name: 'Choose destination', exact: true }).click();
  await page.getByRole('radio', { name: 'Create independent copy', exact: false }).check();
  await page.getByRole('button', { name: 'Prepare and check dependencies', exact: true }).click();
  await page.getByText('Checks passed. Ready to confirm restoration.', { exact: true }).waitFor();
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth));
  await page.screenshot({ path: join(output, 'storybook-dark-900.png'), fullPage: true });
  assert.deepEqual(errors, []);
  await writeFile(join(output, 'storybook.json'), JSON.stringify({ result: 'passed', checks: ['missing dependency blocks confirmation; local import enables confirmation; completed receipt stays available', '900px dark English independent copy has no horizontal overflow'], errors }, null, 2));
  console.log('Restore Storybook checks passed');
} finally { await browser?.close(); await clean(); }
