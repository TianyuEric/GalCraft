import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import { resolve, join } from 'node:path';

const require = createRequire(process.env.GALCRAFT_PLAYWRIGHT_PACKAGE ?? import.meta.url);
const { chromium } = require('playwright');
const output = resolve('test-results/latest/round6/project-center');
await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'chrome', headless: true });
const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
const errors = [], checks = [];
page.on('pageerror', error => errors.push(String(error)));
const story = async id => { await page.goto(`http://127.0.0.1:6007/iframe.html?id=${id}&viewMode=story`); };
try {
  await story('product-studio-projects-project-center--library');
  await page.locator('.project-library-item').first().waitFor();
  assert.equal(await page.locator('.project-library-item').count(), 4);
  await page.screenshot({ path: join(output, 'project-center.png'), fullPage: true, animations: 'disabled' });
  await page.getByRole('button', { name: '已固定', exact: false }).click();
  assert.equal(await page.locator('.project-library-item').count(), 2);
  await page.getByRole('button', { name: '全部作品', exact: false }).click();
  await page.getByRole('textbox', { name: '搜索作品名称或路径' }).fill('习作');
  assert.equal(await page.locator('.project-library-item').count(), 1);
  await page.getByRole('textbox', { name: '搜索作品名称或路径' }).fill('');
  await page.getByRole('button', { name: '列表视图', exact: true }).click();
  await page.getByRole('button', { name: '重新定位', exact: true }).click();
  await page.waitForFunction(() => !document.querySelector('.project-library-unavailable'));
  await page.screenshot({ path: join(output, 'project-list.png'), fullPage: true, animations: 'disabled' });
  checks.push('library filtering, path search, list view and relocation');
  await page.getByRole('button', { name: '新建作品', exact: true }).click();
  await page.getByRole('dialog').waitFor();
  await page.setViewportSize({ width: 900, height: 600 });
  assert(await page.getByRole('button', { name: '选择目录并创建', exact: true }).isVisible());
  const creation = await page.locator('.gc-dialog-footer').boundingBox();
  assert(creation.y + creation.height <= 600);
  await page.screenshot({ path: join(output, 'create-project.png'), animations: 'disabled' });
  checks.push('create dialog footer at 900x600');
  await story('product-studio-projects-project-center--dark-japanese');
  await page.locator('.project-library-item').first().waitFor();
  await page.locator('.project-library').scrollIntoViewIfNeeded();
  await page.screenshot({ path: join(output, 'project-center-dark-japanese.png'), fullPage: true, animations: 'disabled' });
  await story('components-shared-controls--scrollable-dialog');
  await page.getByRole('dialog').waitFor();
  const metrics = await page.locator('.gc-dialog').evaluate(dialog => {
    const body = dialog.querySelector('.gc-dialog-body'), footer = dialog.querySelector('.gc-dialog-footer');
    return { overflow: body.scrollHeight > body.clientHeight, footerBottom: footer.getBoundingClientRect().bottom, footerVisible: footer.getBoundingClientRect().top >= 0 };
  });
  assert(metrics.overflow && metrics.footerVisible && metrics.footerBottom <= 600);
  await page.locator('.gc-choice-trigger').click();
  await page.locator('.gc-choice-search').fill('18');
  await page.locator('.gc-choice-item').filter({ hasText: '18' }).click();
  assert.match(await page.locator('.gc-choice-trigger').innerText(), /18/);
  await page.screenshot({ path: join(output, 'long-dialog.png'), animations: 'disabled' });
  await page.getByRole('button', { name: '保存配置', exact: true }).click();
  await page.getByRole('status').filter({ hasText: '配置已保存' }).waitFor();
  checks.push('scrolling form, fixed footer, searchable choice and form submit');
  assert.deepEqual(errors, []);
  await writeFile(join(output, 'report.json'), JSON.stringify({ target: 'Storybook component integration in Chrome', result: 'passed', checks, errors, executedAt: new Date().toISOString() }, null, 2));
  console.log(JSON.stringify({ result: 'passed', checks, output }));
} finally { await browser.close(); }
