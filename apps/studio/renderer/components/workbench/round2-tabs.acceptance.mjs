import { createRequire } from 'node:module';
import { mkdir, writeFile } from 'node:fs/promises';
import assert from 'node:assert/strict';
import { resolve } from 'node:path';
const { chromium } = createRequire(process.env.GALCRAFT_PLAYWRIGHT_PACKAGE ?? import.meta.url)('playwright');
const output = resolve(process.env.GALCRAFT_UI_EVIDENCE_DIR ?? 'test-results/latest/studio-round2/components'); await mkdir(output, { recursive: true });
const browser = await chromium.launch({ channel: 'msedge', headless: true });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const checks = [], errors = []; page.on('pageerror', error => errors.push(error.message));
const order = () => page.locator('[data-document-id]').evaluateAll(nodes => nodes.map(node => node.dataset.documentId));
try {
  await page.goto('http://127.0.0.1:6007/iframe.html?id=product-studio-workbench-workbench-theme-and-controls--light&viewMode=story');
  const strip = page.locator('.gc-wb-documents'); await strip.waitFor();
  await strip.evaluate(node => node.scrollLeft = 510);
  const before = await strip.evaluate(node => node.scrollLeft);
  const visible = await strip.evaluate(node => [...node.children].find(tab => { const a = node.getBoundingClientRect(), b = tab.getBoundingClientRect(); return b.left >= a.left && b.right <= a.right; }).dataset.documentId);
  await page.locator(`[data-document-id="${visible}"] [role=tab]`).click();
  assert.equal(await strip.evaluate(node => node.scrollLeft), before); checks.push('可见标签激活保持 scrollLeft');
  const other = await strip.evaluate(node => [...node.children].find(tab => { const a=node.getBoundingClientRect(), b=tab.getBoundingClientRect(); return tab.dataset.active !== 'true' && b.left >= a.left && b.right <= a.right; }).dataset.documentId);
  await page.locator(`[data-document-id="${other}"] [role=tab]`).click({ button: 'right' });
  await page.getByRole('menuitem', { name: '向左移动', exact: true }).waitFor();
  assert.equal(await page.locator('[data-active=true]').getAttribute('data-document-id'), visible);
  await page.keyboard.press('Escape');
  assert.equal(await page.evaluate(() => document.activeElement?.closest('[data-document-id]')?.getAttribute('data-document-id')), other);
  checks.push('非活动标签菜单取消不激活且恢复焦点');
  await strip.evaluate(node => node.scrollLeft = 0);
  const first = page.locator('[data-document-id="document-0"] [role=tab]'); const third = page.locator('[data-document-id="document-2"] [role=tab]');
  let a=await first.boundingBox(), b=await third.boundingBox();
  await page.mouse.move(a.x+20,a.y+15); await page.mouse.down(); await page.mouse.move(b.x+b.width-3,b.y+15,{steps:12});
  await page.locator('[data-drop]').waitFor(); await page.mouse.up();
  assert.deepEqual((await order()).slice(0,3),['document-1','document-2','document-0']); checks.push('指针拖动提交真实顺序');
  const initial=await order(); a=await first.boundingBox(); b=await third.boundingBox();
  await first.focus(); await page.mouse.move(a.x+20,a.y+15); await page.mouse.down(); await page.mouse.move(b.x+2,b.y+15,{steps:8});
  await page.locator('[data-drop]').waitFor(); await page.keyboard.press('Escape'); await page.mouse.up(); assert.deepEqual(await order(),initial); checks.push('Esc 取消拖动');
  await first.press('Shift+F10'); await page.getByRole('menuitem',{name:'向左移动',exact:true}).click();
  assert.deepEqual((await order()).slice(0,3),['document-1','document-0','document-2']); checks.push('键盘菜单排序');
  await page.screenshot({path:resolve(output,'tabs-light.png')});
  await page.setViewportSize({width:900,height:760}); await page.goto('http://127.0.0.1:6007/iframe.html?id=product-studio-workbench-workbench-theme-and-controls--dusk&viewMode=story'); await strip.waitFor();
  assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth),900); await page.screenshot({path:resolve(output,'tabs-dusk-900.png')});
  checks.push('900px 暮色无整页横向溢出'); assert.deepEqual(errors,[]);
} finally { await writeFile(resolve(output,'tabs.json'),JSON.stringify({environment:'正式 Storybook / Edge / 内存文档',checks,errors},null,2)); await browser.close(); }
