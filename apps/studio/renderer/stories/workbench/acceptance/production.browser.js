async (page) => {
  const results=[];
  const check=(ok,label)=>{if(!ok)throw new Error(label);results.push(label)};
  const go=async(id)=>{await page.goto('http://127.0.0.1:6007/iframe.html?id=product-studio-workbench-layout-fixtures--'+id+'&viewMode=story');await page.locator('.gc-workbench').waitFor();};
  await page.setViewportSize({width:1440,height:900});
  await go('empty-input');
  await page.getByRole('button',{name:'检查发送',exact:true}).click();
  await page.waitForFunction(()=>document.activeElement?.getAttribute('aria-label')==='朗读文本1');
  check(await page.getByRole('alert').count()===4,'空朗读文本逐行报错，定位到第一处输入');
  await page.getByRole('textbox',{name:'朗读文本1',exact:true}).fill('只生成这一句');
  await page.getByRole('checkbox',{name:'选择我第2句'}).uncheck();
  await page.getByRole('checkbox',{name:'选择小杏第3句'}).uncheck();
  await page.getByRole('button',{name:'检查发送',exact:true}).click();
  check((await page.locator('.gc-wb-sent-input').textContent()).includes('只生成这一句'),'审阅使用修改后的朗读内容');
  check((await page.locator('.gc-wb-key-value').allTextContents()).includes('文字生成请求0'),'配音不调用文字模型');
  await page.getByRole('slider').fill('1.2');
  check(await page.getByRole('textbox',{name:'朗读文本1'}).isVisible(),'参数修改使计划失效并保留输入');
  await page.getByRole('button',{name:'删除草稿',exact:true}).click();
  await page.waitForFunction(()=>document.activeElement?.textContent==='取消');
  check(await page.getByRole('alertdialog').isVisible(),'删除经过独立MessageBox，默认取消');
  await page.keyboard.press('Tab');await page.keyboard.press('Tab');
  await page.waitForFunction(()=>!!document.activeElement?.closest('[role="alertdialog"]'));
  check(await page.evaluate(()=>!!document.activeElement?.closest('[role="alertdialog"]')),'MessageBox焦点保持在确认区域');
  await page.keyboard.press('Escape');
  await page.waitForFunction(()=>document.activeElement?.textContent==='删除草稿');
  check((await page.getByRole('textbox',{name:'朗读文本1'}).inputValue())==='只生成这一句','取消删除返回触发点且保留输入');
  await go('partial-failure');
  check(await page.locator('audio').count()===2,'部分失败保留两句成功候选');
  await page.getByRole('button',{name:'仅重试失败句'}).click();
  await page.waitForFunction(()=>document.querySelectorAll('audio').length===3);
  check(await page.locator('audio').count()===3,'仅重试失败句后补齐三句候选');
  await go('ui-asset-workstation');
  check(await page.getByRole('textbox',{name:'视觉要求'}).isVisible(),'UI素材使用独立视觉输入');
  check(await page.getByRole('combobox',{name:/场景|语句/}).count()===0,'UI素材不显示场景和语句选择');
  await page.getByRole('spinbutton',{name:'输出高度 · px'}).fill('96');
  await page.getByRole('button',{name:'检查发送',exact:true}).click();
  check((await page.locator('.gc-wb-key-value').allTextContents()).includes('输出320 × 96 · 透明'),'UI尺寸进入实际审阅');
  await go('recipe-library');
  for(const name of ['复制到个人','复制到作品','导出'])check(await page.getByRole('button',{name,exact:true}).isVisible(),name+'常驻可见');
  await page.getByRole('button',{name:'NovelAI · 场景背景',exact:true}).click();
  await page.getByRole('button',{name:'使用方案',exact:true}).click();
  check((await page.getByRole('combobox',{name:'执行方案'}).textContent()).includes('NovelAI'),'NovelAI方案进入对应图像方法');
  check(await page.getByRole('textbox',{name:'ComfyUI 执行图'}).count()===0,'NovelAI不残留ComfyUI执行图');
  await go('recipe-library');
  await page.getByRole('button',{name:'复制到个人',exact:true}).click();
  await page.getByRole('textbox',{name:'方案名称'}).fill('我的新声音方案');
  await page.getByRole('button',{name:'关闭编辑',exact:true}).click();
  await page.getByRole('checkbox',{name:'模拟保存失败'}).check();
  await page.getByRole('button',{name:'保存并关闭',exact:true}).click();
  check(await page.getByRole('alertdialog').isVisible(),'保存失败保持MessageBox');
  check((await page.getByRole('alert').textContent()).includes('本次输入已保留'),'失败在确认框就近显示');
  await page.getByRole('button',{name:'继续编辑',exact:true}).click();
  check((await page.getByRole('textbox',{name:'方案名称'}).inputValue())==='我的新声音方案','保存失败后修改内容保留');
  await page.setViewportSize({width:900,height:620});
  for(const name of ['复制到个人','复制到作品','导出'])check(await page.getByRole('button',{name,exact:true}).isVisible(),'窄窗口仍显示'+name);
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'900px无页面横向溢出');
  await page.screenshot({path:'test-results/latest/workbench-storybook/06-library-900.png'});
  return results;
}
